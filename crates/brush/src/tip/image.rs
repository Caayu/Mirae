//! Grayscale image tips with a prefiltered mip pyramid.

use std::sync::{Arc, OnceLock};

use serde::{Deserialize, Serialize};

use crate::rng::StrokeRng;

/// Square grayscale coverage image with box-filtered mip levels, sampled
/// trilinearly so a tip looks the same (no aliasing, no shimmer) whether it
/// is drawn at 5 px or 500 px.
#[derive(Clone, Debug, PartialEq)]
pub struct TipImage {
    /// `(size, texels)` from full size down to 1x1.
    levels: Vec<(u32, Vec<f32>)>,
}

impl TipImage {
    /// `pixels` is `size²` row-major bytes (0 = empty, 255 = full).
    pub fn from_gray(size: u32, pixels: &[u8]) -> Option<Self> {
        if size == 0 || size > 4096 || pixels.len() != (size * size) as usize {
            return None;
        }
        Some(Self::from_f32(
            size,
            pixels.iter().map(|&p| p as f32 / 255.0).collect(),
        ))
    }

    fn from_f32(size: u32, data: Vec<f32>) -> Self {
        let mut levels = vec![(size, data)];
        while levels.last().unwrap().0 > 1 {
            let (s, src) = levels.last().unwrap();
            let (s, n) = (*s as usize, (*s / 2).max(1) as usize);
            let mut dst = vec![0.0; n * n];
            for y in 0..n {
                for x in 0..n {
                    let (x1, y1) = ((2 * x + 1).min(s - 1), (2 * y + 1).min(s - 1));
                    dst[y * n + x] = 0.25
                        * (src[2 * y * s + 2 * x]
                            + src[2 * y * s + x1]
                            + src[y1 * s + 2 * x]
                            + src[y1 * s + x1]);
                }
            }
            levels.push((n as u32, dst));
        }
        Self { levels }
    }

    pub fn size(&self) -> u32 {
        self.levels[0].0
    }

    fn bilinear(&self, level: usize, u: f32, v: f32) -> f32 {
        let (s, data) = &self.levels[level.min(self.levels.len() - 1)];
        let s = *s as i32;
        let (x, y) = (u * s as f32 - 0.5, v * s as f32 - 0.5);
        let (x0, y0) = (x.floor(), y.floor());
        let (fx, fy) = (x - x0, y - y0);
        // Outside the image is empty, so tips fade out at their border.
        let at = |xi: i32, yi: i32| {
            if xi < 0 || yi < 0 || xi >= s || yi >= s {
                0.0
            } else {
                data[(yi * s + xi) as usize]
            }
        };
        let (x0, y0) = (x0 as i32, y0 as i32);
        let top = at(x0, y0) + (at(x0 + 1, y0) - at(x0, y0)) * fx;
        let bottom = at(x0, y0 + 1) + (at(x0 + 1, y0 + 1) - at(x0, y0 + 1)) * fx;
        top + (bottom - top) * fy
    }

    /// Trilinear sample at `(u, v)` in `[0, 1]²` and level of detail `lod`
    /// (`log2` of texels per screen pixel).
    pub fn sample(&self, u: f32, v: f32, lod: f32) -> f32 {
        let lod = lod.clamp(0.0, (self.levels.len() - 1) as f32);
        let l0 = lod.floor() as usize;
        let t = lod - l0 as f32;
        let a = self.bilinear(l0, u, v);
        if t <= 0.0 {
            return a;
        }
        a + (self.bilinear(l0 + 1, u, v) - a) * t
    }
}

/// Image tips generated by the engine itself.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BuiltinTip {
    /// Cluster of soft dots, for grainy and dry media.
    Speckle,
    /// Parallel streaks, like a flat bristle brush.
    Bristle,
    /// Irregular blob with a ragged rim.
    Charcoal,
    #[serde(other)]
    Unknown,
}

const BUILTIN_SIZE: u32 = 256;

impl BuiltinTip {
    pub fn image(self) -> Arc<TipImage> {
        static CACHE: [OnceLock<Arc<TipImage>>; 4] = [const { OnceLock::new() }; 4];
        let i = match self {
            Self::Speckle => 0,
            Self::Bristle => 1,
            Self::Charcoal => 2,
            Self::Unknown => 3,
        };
        CACHE[i]
            .get_or_init(|| Arc::new(TipImage::from_f32(BUILTIN_SIZE, self.generate())))
            .clone()
    }

    fn generate(self) -> Vec<f32> {
        let n = BUILTIN_SIZE as usize;
        let rng = StrokeRng::new(0xB0B5 + self as u64);
        let mut img = vec![0.0f32; n * n];
        let disc = |x: f32, y: f32| (1.0 - (x * x + y * y)).max(0.0);
        match self {
            Self::Speckle => {
                for k in 0..90u64 {
                    let a = rng.uniform(1, k) * std::f32::consts::TAU;
                    let r = rng.uniform(2, k).sqrt() * 0.8;
                    let (cx, cy) = (r * a.cos(), r * a.sin());
                    let rad = 0.04 + 0.08 * rng.uniform(3, k);
                    let w = 0.5 + 0.5 * rng.uniform(4, k);
                    splat(&mut img, n, cx, cy, rad, w);
                }
            }
            Self::Bristle => {
                for (i, px) in img.iter_mut().enumerate() {
                    let (x, y) = (i % n, i / n);
                    let (u, v) = (
                        x as f32 / n as f32 * 2.0 - 1.0,
                        y as f32 / n as f32 * 2.0 - 1.0,
                    );
                    let lane = ((v + 1.0) * 14.0) as u64;
                    let strength = 0.35 + 0.65 * rng.uniform(5, lane);
                    let ends = 1.0 - (u.abs() / (0.75 + 0.25 * rng.uniform(6, lane))).powi(6);
                    let stripe = 0.5 + 0.5 * ((v + 1.0) * 14.0 * std::f32::consts::PI).sin().abs();
                    *px = (strength * ends.max(0.0) * stripe * disc(u * 0.6, v)).clamp(0.0, 1.0);
                }
            }
            Self::Charcoal | Self::Unknown => {
                for (i, px) in img.iter_mut().enumerate() {
                    let (x, y) = (i % n, i / n);
                    let (u, v) = (
                        x as f32 / n as f32 * 2.0 - 1.0,
                        y as f32 / n as f32 * 2.0 - 1.0,
                    );
                    let angle = v.atan2(u) / std::f32::consts::TAU + 0.5;
                    let rim = 0.75
                        + 0.2 * (rng.noise(7, angle * 12.0) - 0.5)
                        + 0.1 * (rng.noise(8, angle * 40.0) - 0.5);
                    let r = (u * u + v * v).sqrt() / rim;
                    let grain = 0.7 + 0.3 * rng.uniform(9, i as u64);
                    *px = (crate::tip::falloff(r.powi(3)) * grain).clamp(0.0, 1.0);
                }
            }
        }
        img
    }
}

fn splat(img: &mut [f32], n: usize, cx: f32, cy: f32, rad: f32, weight: f32) {
    let to_px = |c: f32| (c * 0.5 + 0.5) * n as f32;
    let (px, py, pr) = (to_px(cx), to_px(cy), rad * 0.5 * n as f32);
    let (x0, x1) = (
        (px - pr).floor().max(0.0) as usize,
        ((px + pr).ceil() as usize).min(n),
    );
    let (y0, y1) = (
        (py - pr).floor().max(0.0) as usize,
        ((py + pr).ceil() as usize).min(n),
    );
    for y in y0..y1 {
        for x in x0..x1 {
            let d = ((x as f32 + 0.5 - px).powi(2) + (y as f32 + 0.5 - py).powi(2)).sqrt() / pr;
            let v = &mut img[y * n + x];
            *v = (*v + weight * crate::tip::falloff(d)).min(1.0);
        }
    }
}

#[cfg(test)]
mod tests {
    use glam::Vec2;

    use super::*;
    use crate::Dab;
    use crate::tip::{DabShape, Tip, TipImageSource, TipShape};

    fn disc_image(size: u32) -> Vec<u8> {
        (0..size * size)
            .map(|i| {
                let (x, y) = ((i % size) as f32 + 0.5, (i / size) as f32 + 0.5);
                let c = size as f32 / 2.0;
                let d = ((x - c).powi(2) + (y - c).powi(2)).sqrt();
                if d <= c - 1.0 { 255 } else { 0 }
            })
            .collect()
    }

    fn coverage_sum(tip: &Tip, radius: f32, angle: f32, offset: f32) -> f32 {
        let prepared = tip.prepare();
        let d = Dab {
            center: Vec2::new(600.0 + offset, 600.0 + offset * 0.7),
            radius,
            angle,
            hardness: 0.0,
            ..Dab::default()
        };
        let s = DabShape::new(&prepared, &d, true);
        let b = s.bounds();
        let mut total = 0.0;
        for y in b.y0..b.y1 {
            for x in b.x0..b.x1 {
                total += s.coverage(x as f32 + 0.5, y as f32 + 0.5);
            }
        }
        total
    }

    fn image_tip(size: u32, pixels: Vec<u8>) -> Tip {
        Tip {
            shape: TipShape::Image {
                source: TipImageSource::Embedded { size, pixels },
            },
            ..Default::default()
        }
    }

    #[test]
    fn mip_chain_preserves_mean() {
        let img = TipImage::from_gray(64, &disc_image(64)).unwrap();
        let mean = |l: usize| {
            let (s, d) = &img.levels[l];
            d.iter().sum::<f32>() / (*s * *s) as f32
        };
        assert_eq!(img.levels.len(), 7);
        for l in 1..7 {
            assert!((mean(l) - mean(0)).abs() < 1e-4, "level {l}");
        }
    }

    #[test]
    fn image_disc_matches_its_area_at_every_size() {
        let tip = image_tip(128, disc_image(128));
        for size in [5.0f32, 10.0, 25.0, 50.0, 100.0, 250.0, 500.0] {
            let r = size / 2.0;
            let expected = std::f32::consts::PI * (r * 126.0 / 128.0).powi(2);
            let got = coverage_sum(&tip, r, 0.0, 0.0);
            assert!(
                (got / expected - 1.0).abs() < 0.06,
                "size {size}: {got} vs {expected}"
            );
        }
    }

    #[test]
    fn small_image_tip_does_not_shimmer() {
        let tip = Tip {
            shape: TipShape::Image {
                source: TipImageSource::Builtin {
                    name: BuiltinTip::Speckle,
                },
            },
            ..Default::default()
        };
        for size in [5.0f32, 10.0] {
            let sums: Vec<f32> = (0..24)
                .map(|i| coverage_sum(&tip, size / 2.0, i as f32 * 0.26, i as f32 * 0.04))
                .collect();
            let (lo, hi) = sums
                .iter()
                .fold((f32::MAX, 0f32), |(a, b), &s| (a.min(s), b.max(s)));
            assert!(hi / lo < 1.08, "size {size}: {lo}..{hi}");
        }
    }

    #[test]
    fn flips_mirror_the_image() {
        let mut half = vec![0u8; 32 * 32];
        for y in 0..32 {
            for x in 0..16 {
                half[y * 32 + x] = 255;
            }
        }
        let plain = image_tip(32, half.clone()).prepare();
        let flipped = Tip {
            flip_x: true,
            ..image_tip(32, half)
        }
        .prepare();
        let d = Dab {
            center: Vec2::new(100.0, 100.0),
            radius: 20.0,
            ..Dab::default()
        };
        let (a, b) = (
            DabShape::new(&plain, &d, true),
            DabShape::new(&flipped, &d, true),
        );
        assert!(a.coverage(90.0, 100.0) > 0.9 && a.coverage(110.0, 100.0) < 0.1);
        assert!(b.coverage(90.0, 100.0) < 0.1 && b.coverage(110.0, 100.0) > 0.9);
    }

    #[test]
    fn builtin_tips_are_deterministic_and_nonempty() {
        for t in [
            BuiltinTip::Speckle,
            BuiltinTip::Bristle,
            BuiltinTip::Charcoal,
        ] {
            let a = TipImage::from_f32(BUILTIN_SIZE, t.generate());
            assert_eq!(a, *t.image());
            let mean = a.levels.last().unwrap().1[0];
            assert!(mean > 0.03 && mean < 0.9, "{t:?} mean {mean}");
        }
    }

    #[test]
    fn invalid_embedded_images_are_rejected() {
        assert!(TipImage::from_gray(4, &[0; 15]).is_none());
        assert!(TipImage::from_gray(0, &[]).is_none());
        // A preset with a broken image falls back to a round tip.
        let tip = image_tip(4, vec![0; 3]);
        let round = Tip::default();
        assert_eq!(
            coverage_sum(&tip, 5.0, 0.0, 0.0),
            coverage_sum(&round, 5.0, 0.0, 0.0)
        );
    }
}
