//! Brush tips: the shape of a single dab.
//!
//! A tip is evaluated per pixel in *dab-local* coordinates (rotated by the
//! dab angle and scaled by its two radii), so the same code handles size,
//! aspect ratio, angle and flips for every shape.

mod image;

use std::sync::Arc;

pub use image::{BuiltinTip, TipImage};
use serde::{Deserialize, Serialize};
use tela_canvas::IRect;

use crate::Dab;

/// Where an image tip's pixels come from.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum TipImageSource {
    /// Procedurally generated by the engine (no external assets).
    Builtin { name: BuiltinTip },
    /// Square grayscale image stored in the preset, row-major, `size²`
    /// bytes; value = coverage.
    Embedded { size: u32, pixels: Vec<u8> },
}

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum TipShape {
    /// Circle, or ellipse when aspect < 1.
    #[default]
    Round,
    Rectangle,
    Image {
        source: TipImageSource,
    },
    /// Shapes from newer versions render as `Round`.
    #[serde(other)]
    Unknown,
}

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Tip {
    pub shape: TipShape,
    pub flip_x: bool,
    pub flip_y: bool,
}

impl Tip {
    /// Rotational symmetry period in degrees, used to follow directions
    /// without flipping the tip around needlessly.
    pub fn symmetry_period(&self) -> f32 {
        match self.shape {
            TipShape::Round | TipShape::Rectangle | TipShape::Unknown => 180.0,
            TipShape::Image { .. } => 360.0,
        }
    }

    /// Resolves image data once per stroke.
    pub fn prepare(&self) -> PreparedTip {
        let kind = match &self.shape {
            TipShape::Round | TipShape::Unknown => TipKind::Round,
            TipShape::Rectangle => TipKind::Rectangle,
            TipShape::Image { source } => match source {
                TipImageSource::Builtin { name } => TipKind::Image(name.image()),
                TipImageSource::Embedded { size, pixels } => {
                    match TipImage::from_gray(*size, pixels) {
                        Some(img) => TipKind::Image(Arc::new(img)),
                        None => TipKind::Round,
                    }
                }
            },
        };
        PreparedTip {
            kind,
            flip_x: self.flip_x,
            flip_y: self.flip_y,
        }
    }
}

#[derive(Clone, Debug)]
enum TipKind {
    Round,
    Rectangle,
    Image(Arc<TipImage>),
}

/// A tip ready for rasterization during one stroke.
#[derive(Clone, Debug)]
pub struct PreparedTip {
    kind: TipKind,
    flip_x: bool,
    flip_y: bool,
}

impl Default for PreparedTip {
    fn default() -> Self {
        Tip::default().prepare()
    }
}

/// Radial profile of a soft edge: `1` at `t = 0`, `0` at `t = 1`, with zero
/// slope at both ends (no crease at the centre or the rim) and point
/// symmetry around `t = 0.5`, so an anti-aliasing ramp built from it
/// conserves area exactly.
pub fn falloff(t: f32) -> f32 {
    let t = t.clamp(0.0, 1.0);
    1.0 - t * t * (3.0 - 2.0 * t)
}

/// One dab of a tip, with everything that is constant across its pixels
/// precomputed.
#[derive(Clone, Debug)]
pub struct DabShape<'a> {
    cx: f32,
    cy: f32,
    cos: f32,
    sin: f32,
    inv_rx: f32,
    inv_ry: f32,
    hardness: f32,
    aa: bool,
    extent: (f32, f32),
    tip: &'a PreparedTip,
    /// Mip level for image tips.
    lod: f32,
    /// Image tips: how far past the unit square bilinear kernels reach at
    /// the chosen level, in normalized units.
    image_margin: f32,
    /// Width of the anti-aliasing ramp, pixels.
    aa_width: f32,
    /// Samples per axis (1, 2 or 4). Small dabs are supersampled: point
    /// sampling a shape only a few pixels wide makes its coverage flicker as
    /// it moves by subpixels.
    grid: u32,
}

/// Dabs whose smaller radius is below these many pixels get a 2x2 and
/// a 4x4 stratified sample grid respectively.
const SUPERSAMPLE_2X2_BELOW: f32 = 3.0;
const SUPERSAMPLE_4X4_BELOW: f32 = 1.5;

impl<'a> DabShape<'a> {
    pub fn new(tip: &'a PreparedTip, dab: &Dab, anti_aliasing: bool) -> Self {
        let rx = dab.radius.max(0.25);
        let ry = (dab.radius * dab.aspect.clamp(0.01, 1.0)).max(0.25);
        let (sin, cos) = dab.angle.sin_cos();
        let (lod, image_margin) = match &tip.kind {
            TipKind::Image(img) => {
                let lod = (img.size() as f32 / (2.0 * ry.min(rx))).max(1.0).log2();
                let texel = (lod.ceil().exp2()) / img.size() as f32;
                (lod, 2.0 * texel)
            }
            _ => (0.0, 0.0),
        };
        let grow = 1.0 + image_margin;
        let (ac, as_) = ((rx * grow * cos).abs(), (rx * grow * sin).abs());
        let (bc, bs) = ((ry * grow * cos).abs(), (ry * grow * sin).abs());
        let extent = match tip.kind {
            TipKind::Round => ((ac * ac + bs * bs).sqrt(), (as_ * as_ + bc * bc).sqrt()),
            TipKind::Rectangle | TipKind::Image(_) => (ac + bs, as_ + bc),
        };
        let rmin = rx.min(ry);
        let grid = if !anti_aliasing || rmin >= SUPERSAMPLE_2X2_BELOW {
            1
        } else if rmin >= SUPERSAMPLE_4X4_BELOW {
            2
        } else {
            4
        };
        Self {
            cx: dab.center.x,
            cy: dab.center.y,
            cos,
            sin,
            inv_rx: 1.0 / rx,
            inv_ry: 1.0 / ry,
            hardness: dab.hardness.clamp(0.0, 1.0),
            aa: anti_aliasing,
            extent,
            tip,
            lod,
            image_margin,
            aa_width: 1.0 / grid as f32,
            grid,
        }
    }

    /// Pixels that may receive coverage.
    pub fn bounds(&self) -> IRect {
        let (ex, ey) = (self.extent.0 + 1.0, self.extent.1 + 1.0);
        IRect::enclosing(self.cx - ex, self.cy - ey, self.cx + ex, self.cy + ey)
    }

    /// Coverage `0..=1` of the pixel centred at a canvas point.
    #[inline]
    pub fn coverage(&self, px: f32, py: f32) -> f32 {
        if self.grid == 1 {
            return self.point(px, py);
        }
        let n = self.grid;
        let step = 1.0 / n as f32;
        let mut total = 0.0;
        for j in 0..n {
            for i in 0..n {
                let ox = (i as f32 + 0.5) * step - 0.5;
                let oy = (j as f32 + 0.5) * step - 0.5;
                total += self.point(px + ox, py + oy);
            }
        }
        total * step * step
    }

    #[inline]
    fn point(&self, px: f32, py: f32) -> f32 {
        let (dx, dy) = (px - self.cx, py - self.cy);
        // Dab-local, normalized so the tip boundary is at |q| = 1.
        let qx = (dx * self.cos + dy * self.sin) * self.inv_rx;
        let qy = (dy * self.cos - dx * self.sin) * self.inv_ry;
        match &self.tip.kind {
            TipKind::Round => {
                let r2 = qx * qx + qy * qy;
                if r2 >= 4.0 {
                    return 0.0;
                }
                let r = r2.sqrt();
                // Normalized units per pixel along this direction (|grad r|).
                let gx = qx * self.inv_rx;
                let gy = qy * self.inv_ry;
                let per_px = if r > 1e-6 {
                    (gx * gx + gy * gy).sqrt() / r
                } else {
                    self.inv_rx.max(self.inv_ry)
                };
                self.edge(r, per_px)
            }
            TipKind::Rectangle => {
                let (ax, ay) = (qx.abs(), qy.abs());
                let (r, per_px) = if ax >= ay {
                    (ax, self.inv_rx)
                } else {
                    (ay, self.inv_ry)
                };
                if r >= 2.0 {
                    return 0.0;
                }
                self.edge(r, per_px)
            }
            TipKind::Image(img) => {
                let u = if self.tip.flip_x { -qx } else { qx };
                let v = if self.tip.flip_y { -qy } else { qy };
                let limit = 1.0 + self.image_margin;
                if u.abs() >= limit || v.abs() >= limit {
                    return 0.0;
                }
                let a = img.sample(u * 0.5 + 0.5, v * 0.5 + 0.5, self.lod);
                // Hardness raises contrast around the mid value.
                let half = 0.45 * self.hardness;
                ((a - half) / (1.0 - 2.0 * half)).clamp(0.0, 1.0)
            }
        }
    }

    /// Radial ramp from `start` to half the AA width past the boundary. It
    /// is never narrower than the AA width, so hardness 1 becomes an
    /// anti-aliased edge and lower hardness widens it continuously. The
    /// profile is symmetric, so the edge neither grows nor shrinks the area.
    #[inline]
    fn edge(&self, r: f32, per_px: f32) -> f32 {
        if !self.aa {
            if self.hardness >= 1.0 {
                return if r < 1.0 { 1.0 } else { 0.0 };
            }
            return falloff((r - self.hardness) / (1.0 - self.hardness));
        }
        let half = 0.5 * self.aa_width * per_px;
        let start = self.hardness.min(1.0 - half);
        let end = 1.0 + half;
        if r <= start {
            return 1.0;
        }
        falloff((r - start) / (end - start))
    }
}

#[cfg(test)]
mod tests {
    use glam::Vec2;

    use super::*;

    fn dab(radius: f32, hardness: f32, aspect: f32, angle: f32) -> Dab {
        Dab {
            center: Vec2::new(300.3, 300.7),
            radius,
            aspect,
            angle,
            hardness,
            ..Dab::default()
        }
    }

    fn sum(tip: &PreparedTip, d: &Dab) -> f32 {
        let s = DabShape::new(tip, d, true);
        let b = s.bounds();
        let mut total = 0.0;
        for y in b.y0..b.y1 {
            for x in b.x0..b.x1 {
                total += s.coverage(x as f32 + 0.5, y as f32 + 0.5);
            }
        }
        total
    }

    fn round() -> PreparedTip {
        Tip::default().prepare()
    }

    #[test]
    fn hard_round_area_matches_disc_at_every_size() {
        for size in [5.0, 10.0, 25.0, 50.0, 100.0, 250.0, 500.0] {
            let r: f32 = size / 2.0;
            let area = std::f32::consts::PI * r * r;
            let got = sum(&round(), &dab(r, 1.0, 1.0, 0.0));
            assert!(
                (got / area - 1.0).abs() < 0.03,
                "size {size}: {got} vs {area}"
            );
        }
    }

    #[test]
    fn coverage_is_stable_under_subpixel_motion_and_rotation() {
        let tips = [
            round(),
            Tip {
                shape: TipShape::Rectangle,
                ..Default::default()
            }
            .prepare(),
        ];
        for tip in &tips {
            for size in [5.0f32, 25.0] {
                let mut sums = vec![];
                for i in 0..20 {
                    let mut d = dab(size / 2.0, 0.8, 0.4, i as f32 * 0.31);
                    d.center += Vec2::splat(i as f32 * 0.05);
                    sums.push(sum(tip, &d));
                }
                let (lo, hi) = sums
                    .iter()
                    .fold((f32::MAX, 0f32), |(a, b), &s| (a.min(s), b.max(s)));
                assert!(hi / lo < 1.04, "size {size}: {lo}..{hi}");
            }
        }
    }

    #[test]
    fn hardness_changes_appearance_continuously() {
        let mut prev = sum(&round(), &dab(50.0, 0.0, 1.0, 0.0));
        for i in 1..=100 {
            let s = sum(&round(), &dab(50.0, i as f32 / 100.0, 1.0, 0.0));
            assert!(s >= prev - 1e-3, "harder tips cover at least as much");
            assert!(s - prev < 0.02 * s, "jump at hardness {i}%");
            prev = s;
        }
    }

    #[test]
    fn soft_profile_is_monotone_without_steps() {
        let tip = round();
        let d = dab(250.0, 0.0, 1.0, 0.0);
        let s = DabShape::new(&tip, &d, true);
        let mut prev = 1.0;
        for x in 0..260 {
            let c = s.coverage(d.center.x + x as f32, d.center.y);
            assert!(c <= prev + 1e-6);
            // Below one 8-bit level per pixel: no visible step from the function.
            assert!(prev - c <= 2.0 / 255.0, "step at {x}: {}", prev - c);
            prev = c;
        }
        assert_eq!(s.coverage(d.center.x + 252.0, d.center.y), 0.0);
    }

    #[test]
    fn ellipse_area_and_orientation() {
        let r = 40.0;
        let area = std::f32::consts::PI * r * r * 0.25;
        let got = sum(&round(), &dab(r, 1.0, 0.25, 0.7));
        assert!((got / area - 1.0).abs() < 0.03, "{got} vs {area}");
        // Major axis along the angle.
        let d = dab(r, 1.0, 0.25, 0.0);
        let tip = round();
        let s = DabShape::new(&tip, &d, true);
        assert!(s.coverage(d.center.x + 35.0, d.center.y) > 0.99);
        assert_eq!(s.coverage(d.center.x, d.center.y + 35.0), 0.0);
    }

    #[test]
    fn rectangle_area() {
        let tip = Tip {
            shape: TipShape::Rectangle,
            ..Default::default()
        }
        .prepare();
        let got = sum(&tip, &dab(20.0, 1.0, 0.5, 0.3));
        let area = 40.0 * 20.0;
        assert!((got / area - 1.0).abs() < 0.03, "{got} vs {area}");
    }

    #[test]
    fn falloff_shape() {
        assert_eq!(falloff(0.0), 1.0);
        assert_eq!(falloff(1.0), 0.0);
        assert_eq!(falloff(-3.0), 1.0);
        assert!((falloff(0.5) - 0.5).abs() < 1e-6);
        let integral: f32 = (0..1000)
            .map(|i| falloff((i as f32 + 0.5) / 1000.0))
            .sum::<f32>()
            / 1000.0;
        assert!(
            (integral - 0.5).abs() < 1e-4,
            "symmetric ramp conserves area"
        );
    }

    #[test]
    fn unknown_shape_deserializes_as_round() {
        let t: Tip =
            serde_json::from_str(r#"{"shape":{"kind":"hologram"},"flip_x":true}"#).unwrap();
        assert_eq!(t.shape, TipShape::Unknown);
        assert!(t.flip_x);
        let s = sum(&t.prepare(), &dab(10.0, 1.0, 1.0, 0.0));
        assert!((s - sum(&round(), &dab(10.0, 1.0, 1.0, 0.0))).abs() < 1e-3);
    }
}
